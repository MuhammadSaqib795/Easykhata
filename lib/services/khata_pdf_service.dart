/// Customer Khata statement as a PDF.
///
/// Figures come from the same ledger logic the Khata screen uses
/// ([buildLedgerLines]): "You Gave" raises the balance (they owe you),
/// "You Got" lowers it. Final balance = the customer's balance.
class KhataPdfService {
  const KhataPdfService._();

  static const _ink = PdfColor.fromInt(0xFF0F172A);
  static const _muted = PdfColor.fromInt(0xFF64748B);
  static const _border = PdfColor.fromInt(0xFFE2E8F0);
  static const _headerFill = PdfColor.fromInt(0xFF111827);
  static const _zebra = PdfColor.fromInt(0xFFF8FAFC);
  static const _receivable = PdfColor.fromInt(0xFF15803D);
  static const _payable = PdfColor.fromInt(0xFFB91C1C);

  /// `EasyKhata_<Customer>_<yyyy-MM-dd>.pdf`, safe for any file system.
  static String fileNameFor(String customerName, DateTime date) {
    var safe = customerName
        .replaceAll(RegExp(r'[\\/:*?"<>|\x00-\x1F]'), '')
        .trim()
        .replaceAll(RegExp(r'\s+'), '_');
    if (safe.length > 40) safe = safe.substring(0, 40);
    if (safe.isEmpty) safe = 'Customer';
    final d =
        '${date.year}-${date.month.toString().padLeft(2, '0')}-'
        '${date.day.toString().padLeft(2, '0')}';
    return 'EasyKhata_${safe}_$d.pdf';
  }

  /// Plain amount: "Rs. 1,200" (you will get) or "Rs. -300" (you will pay).
  static String _balanceText(double v) => formatMoney(v);

  static Future<Uint8List> buildCustomerStatement({
    required Customermodel customer,
    required List<TransactionModel> newestFirst,
    DateTime? generatedAt,
  }) async {
    final now = generatedAt ?? DateTime.now();
    final logo = pw.MemoryImage(
      (await rootBundle.load(AppBrand.logoAsset)).buffer.asUint8List(),
    );

    // Statement order: oldest first.
    final lines = buildLedgerLines(
      newestFirst,
      customer.currentBalance,
    ).reversed.toList();

    var totalGave = 0.0;
    var totalGot = 0.0;
    for (final l in lines) {
      if (l.isGave) {
        totalGave += l.transaction.amount;
      } else {
        totalGot += l.transaction.amount;
      }
    }
    final opening = lines.isEmpty ? 0.0 : lines.first.before;
    final finalBalance = roundMoney(customer.currentBalance);

    final rows = <List<String>>[
      if (lines.isNotEmpty && opening != 0)
        ['', 'Balance brought forward', '', '', _balanceText(opening)],
      for (final l in lines)
        [
          formatDate(l.transaction.dateTime),
          l.transaction.desp.trim().isEmpty
              ? (l.isGave ? 'You gave' : 'You got')
              : l.transaction.desp.trim(),
          l.isGave ? formatMoney(l.transaction.amount) : '',
          l.isGave ? '' : formatMoney(l.transaction.amount),
          _balanceText(l.after),
        ],
    ];

    final doc = pw.Document(
      title: 'Customer Khata Statement - ${customer.name}',
      author: AppBrand.name,
      creator: AppBrand.name,
    );

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(36, 36, 36, 40),
        header: (ctx) => ctx.pageNumber == 1
            ? pw.SizedBox()
            : pw.Container(
                margin: const pw.EdgeInsets.only(bottom: 12),
                child: pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Text(
                      'EASY KHATA',
                      style: pw.TextStyle(
                        fontWeight: pw.FontWeight.bold,
                        color: _ink,
                        letterSpacing: 1.2,
                      ),
                    ),
                    pw.Text(
                      'Statement - ${customer.name}',
                      style: const pw.TextStyle(fontSize: 9, color: _muted),
                    ),
                  ],
                ),
              ),
        footer: (ctx) => pw.Container(
          margin: const pw.EdgeInsets.only(top: 12),
          padding: const pw.EdgeInsets.only(top: 8),
          decoration: const pw.BoxDecoration(
            border: pw.Border(top: pw.BorderSide(color: _border)),
          ),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text(
                'Generated by Easy Khata on ${formatDateTime(now)}',
                style: const pw.TextStyle(fontSize: 8.5, color: _muted),
              ),
              pw.Text(
                'Page ${ctx.pageNumber} of ${ctx.pagesCount}',
                style: const pw.TextStyle(fontSize: 8.5, color: _muted),
              ),
            ],
          ),
        ),
        build: (ctx) => [
          _brandHeader(logo),
          pw.SizedBox(height: 18),
          _customerBlock(customer, now, lines),
          pw.SizedBox(height: 18),
          if (lines.isEmpty)
            pw.Container(
              width: double.infinity,
              padding: const pw.EdgeInsets.symmetric(vertical: 36),
              decoration: pw.BoxDecoration(
                border: pw.Border.all(color: _border),
                borderRadius: pw.BorderRadius.circular(8),
              ),
              alignment: pw.Alignment.center,
              child: pw.Text(
                'No transactions found for this customer.',
                style: const pw.TextStyle(color: _muted, fontSize: 11),
              ),
            )
          else
            pw.TableHelper.fromTextArray(
              headers: const ['Date', 'Description', 'You Gave', 'You Got', 'Balance'],
              data: rows,
              headerCount: 1,
              border: null,
              headerDecoration: const pw.BoxDecoration(color: _headerFill),
              headerStyle: pw.TextStyle(
                color: PdfColors.white,
                fontWeight: pw.FontWeight.bold,
                fontSize: 9.5,
              ),
              cellStyle: const pw.TextStyle(fontSize: 9.5, color: _ink),
              cellPadding: const pw.EdgeInsets.symmetric(
                horizontal: 6,
                vertical: 6,
              ),
              rowDecoration: const pw.BoxDecoration(
                border: pw.Border(
                  bottom: pw.BorderSide(color: _border, width: 0.6),
                ),
              ),
              oddRowDecoration: const pw.BoxDecoration(
                color: _zebra,
                border: pw.Border(
                  bottom: pw.BorderSide(color: _border, width: 0.6),
                ),
              ),
              columnWidths: const {
                0: pw.FixedColumnWidth(68),
                1: pw.FlexColumnWidth(),
                2: pw.FixedColumnWidth(74),
                3: pw.FixedColumnWidth(74),
                4: pw.FixedColumnWidth(88),
              },
              cellAlignments: const {
                0: pw.Alignment.centerLeft,
                1: pw.Alignment.centerLeft,
                2: pw.Alignment.centerRight,
                3: pw.Alignment.centerRight,
                4: pw.Alignment.centerRight,
              },
              headerAlignments: const {
                2: pw.Alignment.centerRight,
                3: pw.Alignment.centerRight,
                4: pw.Alignment.centerRight,
              },
            ),
          pw.SizedBox(height: 18),
          _summary(totalGave, totalGot, finalBalance),
          pw.SizedBox(height: 10),
          pw.Text(
            'You Gave = money or goods you gave the customer. You Got = money '
            'you received. A positive balance is the amount you will get; a '
            'negative balance (-) is the amount you will pay.',
            style: const pw.TextStyle(fontSize: 8, color: _muted),
          ),
        ],
      ),
    );

    return doc.save();
  }

  static pw.Widget _brandHeader(pw.ImageProvider logo) {
    return pw.Row(
      crossAxisAlignment: pw.CrossAxisAlignment.center,
      children: [
        pw.Image(logo, width: 44, height: 44),
        pw.SizedBox(width: 12),
        pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              'EASY KHATA',
              style: pw.TextStyle(
                fontSize: 18,
                fontWeight: pw.FontWeight.bold,
                color: _ink,
                letterSpacing: 1.5,
              ),
            ),
            pw.Text(
              'Customer Khata Statement',
              style: const pw.TextStyle(fontSize: 11, color: _muted),
            ),
          ],
        ),
      ],
    );
  }

  static pw.Widget _customerBlock(
    Customermodel customer,
    DateTime now,
    List<LedgerLine> lines,
  ) {
    pw.Widget field(String label, String value) => pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 4),
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.SizedBox(
            width: 92,
            child: pw.Text(
              label,
              style: const pw.TextStyle(fontSize: 9.5, color: _muted),
            ),
          ),
          pw.Expanded(
            child: pw.Text(
              value,
              style: pw.TextStyle(
                fontSize: 10,
                color: _ink,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
          ),
        ],
      ),
    );

    final phone = customer.phoneNo.trim();
    final address = (customer.address ?? '').trim();
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.all(14),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: _border),
        borderRadius: pw.BorderRadius.circular(8),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          field('Customer', customer.name),
          if (phone.isNotEmpty) field('Phone', phone),
          if (address.isNotEmpty) field('Address', address),
          if (lines.isNotEmpty)
            field(
              'Period',
              '${formatDate(lines.first.transaction.dateTime)} - '
                  '${formatDate(lines.last.transaction.dateTime)}',
            ),
          field('Report generated', formatDateTime(now)),
        ],
      ),
    );
  }

  static pw.Widget _summary(double gave, double got, double balance) {
    final label = balance > 0
        ? 'You Will Get'
        : (balance < 0 ? 'You Will Pay' : 'Account Settled');
    final color = balance > 0
        ? _receivable
        : (balance < 0 ? _payable : _muted);

    pw.Widget row(String l, String v, {bool strong = false, PdfColor? c}) =>
        pw.Padding(
          padding: const pw.EdgeInsets.symmetric(vertical: 3),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text(
                l,
                style: pw.TextStyle(
                  fontSize: strong ? 11.5 : 10,
                  color: c ?? _ink,
                  fontWeight: strong ? pw.FontWeight.bold : null,
                ),
              ),
              pw.Text(
                v,
                style: pw.TextStyle(
                  fontSize: strong ? 12.5 : 10,
                  color: c ?? _ink,
                  fontWeight: pw.FontWeight.bold,
                ),
              ),
            ],
          ),
        );

    return pw.Align(
      alignment: pw.Alignment.centerRight,
      child: pw.Container(
        width: 260,
        padding: const pw.EdgeInsets.all(14),
        decoration: pw.BoxDecoration(
          border: pw.Border.all(color: _border),
          borderRadius: pw.BorderRadius.circular(8),
        ),
        child: pw.Column(
          children: [
            row('Total You Gave', formatMoney(gave)),
            row('Total You Got', formatMoney(got)),
            pw.Divider(color: _border, height: 14),
            row('Final Balance', _balanceText(balance), strong: true),
            row(label, formatMoney(balance.abs()), strong: true, c: color),
          ],
        ),
      ),
    );
  }

  /// System print / "Save as PDF" dialog (download, print, open).
  static Future<void> saveOrPrint(Uint8List bytes, String fileName) =>
      Printing.layoutPdf(onLayout: (_) async => bytes, name: fileName);

  /// Share sheet (WhatsApp, e-mail, Files, …).
  static Future<void> share(Uint8List bytes, String fileName) =>
      Printing.sharePdf(bytes: bytes, filename: fileName);
}
